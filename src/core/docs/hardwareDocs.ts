import { buildGraph, deriveBom, derivePinMap } from '../circuit/graph';
import type { Diagnostic } from '../diagnostics';
import { getRegistry, type HardwareRegistry } from '../registry/registry';
import { LANGUAGE_LABELS, type BoardDefinition, type Language } from '../registry/types';
import type { Circuit, Dependency, HardwareModel } from '../project/schema';

/**
 * Deterministic documentation generated from the project model: hardware list,
 * wiring guide and setup instructions. No AI involved — the AI may enrich these
 * through a reviewed proposal.
 */

function endpointLabel(node: string, pin: string, circuit: Circuit, board: BoardDefinition, registry: HardwareRegistry): string {
  if (node === 'board') {
    const p = registry.resolveBoardPin(board.id, pin);
    return `${board.name.split(' (')[0]} ${p?.label ?? pin}`;
  }
  const inst = circuit.components.find((c) => c.id === node);
  const def = inst ? registry.getComponent(inst.type) : undefined;
  const pinLabel = def?.pins.find((p) => p.id === pin)?.label ?? pin;
  return `${inst?.label ?? node} ${pinLabel}`;
}

export function generateHardwareList(circuit: Circuit, hardware: HardwareModel, registry: HardwareRegistry = getRegistry()): string {
  const board = registry.getBoard(hardware.boardId);
  const lines = ['## Hardware list', ''];
  lines.push('| Qty | Part | Reference | Notes |', '|---:|---|---|---|');
  if (board) lines.push(`| 1 | ${board.name} | — | ${board.mcu}, ${board.logicVoltage} V logic |`);
  for (const l of deriveBom(circuit, registry)) {
    const def = registry.getComponent(l.type);
    const props = circuit.components
      .filter((c) => c.type === l.type)
      .map((c) => {
        const hw = def?.props.filter((p) => !p.simulation) ?? [];
        return hw.map((p) => `${p.label} ${String(c.props[p.key] ?? p.default)}${p.unit ?? ''}`).join(', ');
      })
      .filter(Boolean);
    const uniqueProps = [...new Set(props)].join('; ');
    lines.push(`| ${l.quantity} | ${l.name} | ${l.labels.join(', ')} | ${uniqueProps} |`);
  }
  lines.push('| — | Jumper wires, USB data cable | — | |');
  return lines.join('\n') + '\n';
}

export function generateWiringGuide(circuit: Circuit, hardware: HardwareModel, diagnostics: Diagnostic[] = [], registry: HardwareRegistry = getRegistry()): string {
  const board = registry.getBoard(hardware.boardId);
  if (!board) return `## Wiring\n\nUnknown board "${hardware.boardId}".\n`;
  const graph = buildGraph(circuit, board.id, registry);
  const pinMap = derivePinMap(graph);
  const lines = ['## Wiring', '', '| # | From | To |', '|---:|---|---|'];
  circuit.wires.forEach((w, i) => {
    lines.push(`| ${i + 1} | ${endpointLabel(w.from.node, w.from.pin, circuit, board, registry)} | ${endpointLabel(w.to.node, w.to.pin, circuit, board, registry)} |`);
  });
  if (pinMap.length) {
    lines.push('', '## Pin map', '', '| Signal | Board pin | GPIO | Capabilities |', '|---|---|---:|---|');
    for (const b of pinMap) {
      lines.push(`| ${b.componentLabel}.${b.componentPin}${b.via ? ` (via ${graph.instances.get(b.via)?.label})` : ''} | ${b.boardPin.label} | ${b.boardPin.gpio} | ${b.boardPin.capabilities.join(', ')} |`);
    }
  }
  const notable = diagnostics.filter((d) => d.source === 'hardware' && d.severity !== 'info');
  if (notable.length) {
    lines.push('', '## Validation notes', '');
    for (const d of notable) lines.push(`- **${d.severity.toUpperCase()}** ${d.message}${d.hint ? ` — ${d.hint}` : ''}`);
  }
  return lines.join('\n') + '\n';
}

export function generateHardwareDoc(name: string, circuit: Circuit, hardware: HardwareModel, diagnostics: Diagnostic[] = [], registry: HardwareRegistry = getRegistry()): string {
  const board = registry.getBoard(hardware.boardId);
  const header = [`# ${name} — Hardware`, '', board ? `Target board: **${board.name}** (${board.mcu}, ${board.logicVoltage} V logic${board.fiveVoltTolerant ? ', 5 V tolerant' : ', not 5 V tolerant'}).` : '', ''];
  return [...header, generateHardwareList(circuit, hardware, registry), generateWiringGuide(circuit, hardware, diagnostics, registry), '_Generated by IoT-OS from `.iotos/circuit.json`._', ''].join('\n');
}

export function generateSetupDoc(name: string, board: BoardDefinition, language: Language, deps: Dependency[]): string {
  const lines = [`# ${name} — Setup`, '', `Language: ${LANGUAGE_LABELS[language]} · Board: ${board.name}`, ''];
  if (language === 'arduino-cpp' && board.toolchain.arduino) {
    const tc = board.toolchain.arduino;
    lines.push('## Toolchain', '', 'Install [Arduino CLI](https://arduino.github.io/arduino-cli/latest/installation/), then the board package:', '', '```sh');
    lines.push(tc.indexUrl ? `arduino-cli core update-index --additional-urls ${tc.indexUrl}` : 'arduino-cli core update-index');
    lines.push(tc.indexUrl ? `arduino-cli core install ${tc.core} --additional-urls ${tc.indexUrl}` : `arduino-cli core install ${tc.core}`);
    lines.push('```', '');
    const libs = deps.filter((d) => d.ecosystem === 'arduino');
    if (libs.length) {
      lines.push('## Libraries', '', '```sh');
      for (const l of libs) lines.push(`arduino-cli lib install "${l.name}${l.version ? `@${l.version}` : ''}"`);
      lines.push('```', '');
    }
    lines.push('## Build and upload', '', 'Use **Build** and **Upload** in IoT-OS, or the equivalent commands IoT-OS shows in the Build panel.', '');
  } else if (language === 'micropython' && board.toolchain.micropython) {
    const mp = board.toolchain.micropython;
    lines.push('## Firmware', '', `Download MicroPython for this board from ${mp.firmwareUrl}.`, '');
    if (mp.firmwareFlash === 'uf2') lines.push('Hold BOOTSEL while plugging in USB, then copy the `.uf2` file to the RPI-RP2 drive (IoT-OS can do this from the Devices view).', '');
    else lines.push(`Flash it with esptool (IoT-OS: Devices → Install MicroPython), e.g. \`esptool --chip ${mp.esptoolChip} write_flash ${mp.flashOffset} firmware.bin\`.`, '');
    lines.push('## Tools', '', 'Install mpremote: `pip install mpremote`.', '');
    const mip = deps.filter((d) => d.ecosystem === 'micropython-mip');
    if (mip.length) {
      lines.push('## Packages', '', '```sh');
      for (const p of mip) lines.push(`mpremote mip install ${p.name}`);
      lines.push('```', '');
    }
    lines.push('## Deploy', '', 'Use **Upload** in IoT-OS to copy `src/*.py` to the board and reset it.', '');
  }
  return lines.join('\n');
}
